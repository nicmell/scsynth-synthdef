//! The Rust files that `generator/catalog.json` renders into. Each committed
//! file must be the rendering of the JSON. With `SCSYNTH_SYNTHDEF_BLESS=1`
//! set, the test writes them instead.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::Value;

const HEADER: &str = "// @generated by tests/render.rs from generator/catalog.json. Do not edit.\n";

fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

fn catalog() -> Value {
    let text = fs::read_to_string(root().join("generator/catalog.json"))
        .expect("generator/catalog.json reads");
    serde_json::from_str(&text).expect("generator/catalog.json is JSON")
}

fn check(path: &str, rendered: &str) {
    let path = root().join(path);
    if env::var_os("SCSYNTH_SYNTHDEF_BLESS").is_some() {
        fs::write(&path, rendered).expect("the rendered file writes");
        return;
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "{} is not the rendering of generator/catalog.json. \
         Run the tests with SCSYNTH_SYNTHDEF_BLESS=1 to write it.",
        path.display()
    );
}

fn render_operators(catalog: &Value) -> String {
    let mut rendered = String::from(HEADER);
    for (kind, table) in [("unary", "UNARY"), ("binary", "BINARY")] {
        let names = catalog["operators"][kind]
            .as_array()
            .expect("a list of operators");
        writeln!(rendered, "\n/// The {kind} operators, by special index.").unwrap();
        writeln!(
            rendered,
            "pub(super) static {table}: [&str; {}] = [",
            names.len()
        )
        .unwrap();
        for name in names {
            let name = name.as_str().expect("each special index has a name");
            writeln!(rendered, "    {name:?},").unwrap();
        }
        rendered.push_str("];\n");
    }
    rendered
}

#[test]
fn the_operator_tables_are_the_rendering_of_catalog_json() {
    check("src/operator/generated.rs", &render_operators(&catalog()));
}
