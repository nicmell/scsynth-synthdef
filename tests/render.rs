//! The Rust files that `generator/catalog.json` renders into. Each committed
//! file must be the rendering of the JSON. With `SCSYNTH_SYNTHDEF_BLESS=1`
//! set, the test writes them instead.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::Value;

const HEADER: &str = "// @generated by tests/render.rs from generator/catalog.json. Do not edit.\n";

/// The variant of each name of the JSON, by enum.
type Variants = [(&'static str, &'static str)];

const RATES: &Variants = &[
    ("scalar", "Rate::Scalar"),
    ("control", "Rate::Control"),
    ("audio", "Rate::Audio"),
    ("demand", "Rate::Demand"),
];
const KINDS: &Variants = &[
    ("signal", "ArgKind::Signal"),
    ("count", "ArgKind::Count"),
    ("array", "ArgKind::Array"),
    ("symbol", "ArgKind::Symbol"),
    ("bool", "ArgKind::Bool"),
    ("curve", "ArgKind::Curve"),
    ("function", "ArgKind::Function"),
];
const RULES: &Variants = &[
    ("valid", "CheckInputs::Valid"),
    (
        "same_rate_as_first_input",
        "CheckInputs::SameRateAsFirstInput",
    ),
    (
        "same_rate_as_first_input_if_audio",
        "CheckInputs::SameRateAsFirstInputIfAudio",
    ),
    ("buf_wr", "CheckInputs::BufWr"),
    ("duty", "CheckInputs::Duty"),
    ("peak", "CheckInputs::Peak"),
    ("t2k", "CheckInputs::T2K"),
];
const OPTIMIZE: &Variants = &[
    ("nothing", "Optimize::Nothing"),
    ("dead_code", "Optimize::DeadCode"),
    ("binary_op", "Optimize::BinaryOp"),
];
const FFT_SIZES: &Variants = &[
    ("buf_frames", "FftSize::BufFrames"),
    ("input", "FftSize::Input"),
    ("chain", "FftSize::Chain"),
];
const CONVERT_ENVS: &Variants = &[
    ("array", "ConvertEnv::Array"),
    ("interpolation", "ConvertEnv::Interpolation"),
];
const SIGNAL_RANGES: &Variants = &[
    ("bipolar", "SignalRange::Bipolar"),
    ("unipolar", "SignalRange::Unipolar"),
];
const EXPANSIONS: &Variants = &[
    ("elements", "ArrayExpansion::Elements"),
    ("flop", "ArrayExpansion::Flop"),
    ("refs", "ArrayExpansion::Refs"),
];

fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

fn catalog() -> Value {
    let text = fs::read_to_string(root().join("generator/catalog.json"))
        .expect("generator/catalog.json reads");
    serde_json::from_str(&text).expect("generator/catalog.json is JSON")
}

fn check(path: &str, rendered: &str) {
    let path = root().join(path);
    if env::var_os("SCSYNTH_SYNTHDEF_BLESS").is_some() {
        fs::write(&path, rendered).expect("the rendered file writes");
        return;
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "{} is not the rendering of generator/catalog.json. \
         Run the tests with SCSYNTH_SYNTHDEF_BLESS=1 to write it.",
        path.display()
    );
}

fn render_operators(catalog: &Value) -> String {
    let mut rendered = String::from(HEADER);
    for (kind, table) in [("unary", "UNARY"), ("binary", "BINARY")] {
        let names = list(&catalog["operators"][kind]);
        writeln!(rendered, "\n/// The {kind} operators, by special index.").unwrap();
        writeln!(
            rendered,
            "pub(super) static {table}: [&str; {}] = [",
            names.len()
        )
        .unwrap();
        for name in names {
            writeln!(rendered, "    {:?},", text(name)).unwrap();
        }
        rendered.push_str("];\n");
    }
    rendered
}

fn list(value: &Value) -> &[Value] {
    value
        .as_array()
        .unwrap_or_else(|| panic!("{value} is not a list"))
}

fn text(value: &Value) -> &str {
    value
        .as_str()
        .unwrap_or_else(|| panic!("{value} is not a string"))
}

fn boolean(value: &Value) -> bool {
    value
        .as_bool()
        .unwrap_or_else(|| panic!("{value} is not a boolean"))
}

fn number(value: &Value) -> usize {
    let number = value
        .as_u64()
        .unwrap_or_else(|| panic!("{value} is not a count"));
    usize::try_from(number).expect("a count fits usize")
}

fn position(value: &Value) -> String {
    number(value).to_string()
}

fn variant(value: &Value, variants: &Variants) -> String {
    let name = text(value);
    let (_, path) = variants
        .iter()
        .find(|(known, _)| *known == name)
        .unwrap_or_else(|| panic!("{name} is none of {variants:?}"));
    (*path).to_owned()
}

/// `None` for a value that is missing or null, else `Some` of its rendering.
fn optional(value: Option<&Value>, render: impl FnOnce(&Value) -> String) -> String {
    match value {
        None | Some(Value::Null) => "None".to_owned(),
        Some(value) => format!("Some({})", render(value)),
    }
}

/// The one key of an object and its value, as the JSON tags a variant.
fn tagged(value: &Value) -> (&str, &Value) {
    let (tag, inner) = value
        .as_object()
        .and_then(|object| object.iter().next())
        .unwrap_or_else(|| panic!("{value} is not tagged"));
    (tag, inner)
}

fn slice(values: &Value, render: impl FnMut(&Value) -> String) -> String {
    let items: Vec<String> = list(values).iter().map(render).collect();
    format!("&[{}]", items.join(", "))
}

fn strings(values: &Value) -> String {
    slice(values, |value| format!("{:?}", text(value)))
}

fn float(value: &Value) -> String {
    match value {
        Value::String(special) => match special.as_str() {
            "inf" => "f64::INFINITY".to_owned(),
            "-inf" => "f64::NEG_INFINITY".to_owned(),
            "nan" => "f64::NAN".to_owned(),
            other => panic!("{other} is no float"),
        },
        _ => format!("{:?}", value.as_f64().expect("a number")),
    }
}

fn default(value: &Value) -> String {
    optional(Some(value), |value| match tagged(value) {
        ("float", inner) => format!("ArgDefault::Float({})", float(inner)),
        ("symbol", inner) => format!("ArgDefault::Symbol({:?})", text(inner)),
        ("bool", inner) => format!("ArgDefault::Bool({})", boolean(inner)),
        ("floats", inner) => format!("ArgDefault::Floats({})", slice(inner, float)),
        (other, _) => panic!("{other} is no kind of default"),
    })
}

fn check_inputs(value: &Value) -> String {
    match text(&value["rule"]) {
        "n_inputs" => format!("CheckInputs::NInputs({})", number(&value["count"])),
        "audio_at" => format!("CheckInputs::AudioAt({})", number(&value["index"])),
        "audio_from" => format!("CheckInputs::AudioFrom({})", number(&value["index"])),
        "abstract_out" => format!(
            "CheckInputs::AbstractOut {{ fixed: {} }}",
            number(&value["fixed"])
        ),
        "custom" => format!("CheckInputs::Custom({:?})", text(&value["owner"])),
        _ => variant(&value["rule"], RULES),
    }
}

fn outputs(value: &Value) -> String {
    let rate = || variant(&value["rate"], RATES);
    if let Some(rates) = value.get("fixed") {
        format!(
            "Outputs::Fixed({})",
            slice(rates, |rate| variant(rate, RATES))
        )
    } else if let Some(arg) = value.get("arg") {
        format!("Outputs::Arg {{ arg: {}, rate: {} }}", number(arg), rate())
    } else {
        let arg = number(&value["array_size"]);
        format!("Outputs::ArraySize {{ arg: {arg}, rate: {} }}", rate())
    }
}

fn slot(value: &Value) -> String {
    let variant = match tagged(value) {
        ("arg", _) => "Arg",
        ("array", _) => "ArgArray",
        ("string", _) => "ArgString",
        (other, _) => panic!("{other} is no kind of slot"),
    };
    format!("InputSlot::{variant}({})", number(tagged(value).1))
}

/// Writes `name: value,` for each field, at `indent`.
fn fields(rendered: &mut String, indent: &str, fields: &[(&str, String)]) {
    for (name, value) in fields {
        writeln!(rendered, "{indent}{name}: {value},").unwrap();
    }
}

fn render_method(rendered: &mut String, method: &Value) {
    rendered.push_str("            RateMethod {\n");
    let selector = text(&method["selector"]);
    writeln!(rendered, "                selector: {selector:?},").unwrap();
    rendered.push_str("                args: &[\n");
    for arg in list(&method["args"]) {
        writeln!(
            rendered,
            "                    ArgSpec {{ name: {:?}, kind: {}, default: {} }},",
            text(&arg["name"]),
            variant(&arg["kind"], KINDS),
            default(&arg["default"])
        )
        .unwrap();
    }
    rendered.push_str("                ],\n");
    match &method["addable"] {
        Value::Bool(true) => render_wiring(rendered, method),
        Value::Bool(false) => {
            let reason = text(&method["reason"]);
            writeln!(
                rendered,
                "                addable: Addable::No({reason:?}),"
            )
            .unwrap();
        }
        Value::String(state) if state == "pseudo" => {
            rendered.push_str("                addable: Addable::Pseudo,\n");
        }
        other => panic!("{other} is no addable state"),
    }
    rendered.push_str("            },\n");
}

fn render_wiring(rendered: &mut String, method: &Value) {
    let through = |through: &Value| {
        let zero = optional(through.get("zero"), position);
        format!(
            "Passthrough {{ input: {}, zero: {zero} }}",
            number(&through["input"])
        )
    };
    let special_index = method["special_index"].as_i64().expect("a special index");
    let field = |name| method.get(name);
    rendered.push_str("                addable: Addable::Yes(Wiring {\n");
    fields(
        rendered,
        "                    ",
        &[
            ("rate", variant(&method["rate"], RATES)),
            ("inputs", slice(&method["inputs"], slot)),
            ("outputs", outputs(&method["outputs"])),
            ("special_index", special_index.to_string()),
            ("madd", boolean(&method["madd"]).to_string()),
            (
                "nested_expansion",
                boolean(&method["nested_expansion"]).to_string(),
            ),
            ("audio_input", optional(field("audio_input"), position)),
            (
                "audio_together",
                optional(field("audio_together"), |positions| {
                    slice(positions, position)
                }),
            ),
            ("level", field("level").is_some_and(boolean).to_string()),
            ("passthrough", optional(field("passthrough"), through)),
            ("silence", optional(field("silence"), position)),
            (
                "array_expansion",
                optional(field("array_expansion"), |value| variant(value, EXPANSIONS)),
            ),
        ],
    );
    rendered.push_str("                }),\n");
}

/// Writes the `methods` of a class, and closes it.
fn render_class_methods(rendered: &mut String, class: &Value) {
    rendered.push_str("        methods: &[\n");
    for method in list(&class["methods"]) {
        render_method(rendered, method);
    }
    rendered.push_str("        ],\n    },\n");
}

fn render_catalog(catalog: &Value) -> String {
    let classes = list(&catalog["classes"]);
    let mut rendered = String::from(HEADER);
    rendered.push_str("#![allow(clippy::approx_constant, clippy::unreadable_literal)]\n\n");
    rendered.push_str(
        "use super::{\n    Addable, ArgDefault, ArgKind, ArgSpec, ArrayExpansion, CheckInputs, ControlSpec, ConvertEnv,\n    FftSize, InputSlot, Optimize, Outputs, Passthrough, PseudoClass, RateMethod, SignalRange,\n    UGenClass, UGenMethod, Wiring,\n};\nuse crate::rate::Rate;\n\n",
    );
    let count = classes.len();
    writeln!(
        rendered,
        "pub(super) static CLASSES: [UGenClass; {count}] = ["
    )
    .unwrap();
    for class in classes {
        rendered.push_str("    UGenClass {\n");
        fields(
            &mut rendered,
            "        ",
            &[
                ("name", format!("{:?}", text(&class["name"]))),
                ("superclasses", strings(&class["superclasses"])),
                ("is_pure", boolean(&class["pure"]).to_string()),
                ("optimize", variant(&class["optimize"], OPTIMIZE)),
                ("is_width_first", boolean(&class["width_first"]).to_string()),
                (
                    "fft_size",
                    optional(class.get("fft_size"), |value| variant(value, FFT_SIZES)),
                ),
                (
                    "convert_env",
                    optional(class.get("convert_env"), |value| {
                        variant(value, CONVERT_ENVS)
                    }),
                ),
                ("cant_alias", boolean(&class["cant_alias"]).to_string()),
                ("categories", strings(&class["categories"])),
                ("check_inputs", check_inputs(&class["check_inputs"])),
                (
                    "signal_range",
                    variant(&class["signal_range"], SIGNAL_RANGES),
                ),
            ],
        );
        render_class_methods(&mut rendered, class);
    }
    rendered.push_str("];\n");
    render_pseudo_classes(&mut rendered, catalog);
    render_specs(&mut rendered, catalog);
    render_methods(&mut rendered, catalog, "env_methods", "ENV_METHODS");
    render_methods(&mut rendered, catalog, "env_ranges", "ENV_RANGES");
    render_methods(&mut rendered, catalog, "pv_methods", "PV_METHODS");
    render_ugen_methods(&mut rendered, catalog);
    rendered
}

fn render_ugen_methods(rendered: &mut String, catalog: &Value) {
    let methods = list(&catalog["ugen_methods"]);
    let count = methods.len();
    writeln!(
        rendered,
        "\npub(super) static UGEN_METHODS: [UGenMethod; {count}] = ["
    )
    .unwrap();
    let class = |value: &Value| format!("{:?}", text(value));
    for method in methods {
        rendered.push_str("    UGenMethod {\n        method:\n");
        render_method(rendered, method);
        fields(
            rendered,
            "        ",
            &[
                ("number", optional(method.get("number"), class)),
                ("array", optional(method.get("array"), class)),
                ("overrides", strings(&method["overrides"])),
            ],
        );
        rendered.push_str("    },\n");
    }
    rendered.push_str("];\n");
}

fn render_methods(rendered: &mut String, catalog: &Value, key: &str, name: &str) {
    let methods = list(&catalog[key]);
    let count = methods.len();
    writeln!(
        rendered,
        "\npub(super) static {name}: [RateMethod; {count}] = ["
    )
    .unwrap();
    for method in methods {
        render_method(rendered, method);
    }
    rendered.push_str("];\n");
}

fn render_pseudo_classes(rendered: &mut String, catalog: &Value) {
    let classes = list(&catalog["pseudo_classes"]);
    let count = classes.len();
    writeln!(
        rendered,
        "\npub(super) static PSEUDO_CLASSES: [PseudoClass; {count}] = ["
    )
    .unwrap();
    for class in classes {
        rendered.push_str("    PseudoClass {\n");
        fields(
            rendered,
            "        ",
            &[
                ("name", format!("{:?}", text(&class["name"]))),
                ("categories", strings(&class["categories"])),
            ],
        );
        render_class_methods(rendered, class);
    }
    rendered.push_str("];\n");
}

fn render_specs(rendered: &mut String, catalog: &Value) {
    let specs = list(&catalog["specs"]);
    let count = specs.len();
    writeln!(
        rendered,
        "\npub(super) static SPECS: [ControlSpec; {count}] = ["
    )
    .unwrap();
    for spec in specs {
        rendered.push_str("    ControlSpec {\n");
        fields(
            rendered,
            "        ",
            &[
                ("name", format!("{:?}", text(&spec["name"]))),
                ("minval", float(&spec["minval"])),
                ("maxval", float(&spec["maxval"])),
                ("warp", format!("{:?}", text(&spec["warp"]))),
                ("step", float(&spec["step"])),
                ("default", float(&spec["default"])),
                ("units", format!("{:?}", text(&spec["units"]))),
            ],
        );
        rendered.push_str("    },\n");
    }
    rendered.push_str("];\n");
}

#[test]
fn the_operator_tables_are_the_rendering_of_catalog_json() {
    check("src/operator/generated.rs", &render_operators(&catalog()));
}

#[test]
fn the_catalogue_is_the_rendering_of_catalog_json() {
    check("src/catalog/generated.rs", &render_catalog(&catalog()));
}
